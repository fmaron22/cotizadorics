// --- Updates (For Catalog UI) ---

export async function updateMaterial(id: string, data: Partial<MaterialBase>): Promise<MaterialBase> {
    const { customVariables, ...rest } = data;
    const updated = await prisma.materialBase.update({
        where: { id },
        data: {
            ...rest,
            customVariables: customVariables || undefined
        }
    });
    return { ...updated, customVariables: updated.customVariables as Record<string, any> };
}

