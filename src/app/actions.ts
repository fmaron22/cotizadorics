// --- Creation (For Catalog UI) ---

export async function createMaterial(data: MaterialBase): Promise<MaterialBase> {
    const { id, customVariables, ...rest } = data;
    // We let Prisma/DB generate ID if not provided, or use provided one. 
    // Usually standard is to omit ID on create, but our mock had it.
    // If ID is passed and exists, it fails. If ID is empty string or undefined, let DB handle it?
    // Our schema says id string @id @default(uuid()).

    // We'll trust the ID if generated by client (crypto.randomUUID) or let prisma gen it if we omit it.
    // Ideally we omit it.

    // clean data
    const createData: any = { ...rest, customVariables: customVariables || {} };
    if (id && id.length > 5) createData.id = id;

    const created = await prisma.materialBase.create({ data: createData });
    return { ...created, customVariables: created.customVariables as Record<string, any> };
}

