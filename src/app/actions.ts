// --- Getters ---

export async function getMaterials(): Promise<MaterialBase[]> {
    const data = await prisma.materialBase.findMany({ orderBy: { createdAt: 'asc' } });
    return data.map(item => ({
        ...item,
        // Prisma Json type needs casting or validation if strictly typed in TS
        customVariables: item.customVariables as Record<string, any> || {}
    }));
}

